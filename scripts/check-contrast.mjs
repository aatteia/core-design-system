#!/usr/bin/env node
/**
 * Read hex primitives from tokens.css, check WCAG 2.2 pairs, write
 * docs/accessibility.md. Exit 1 if a required pair fails.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const tokensPath = path.join(root, "tokens.css");
const outPath = path.join(root, "docs", "accessibility.md");

function parseHexVars(css) {
  const vars = new Map();
  const re = /--([a-z0-9-]+)\s*:\s*(#[0-9A-Fa-f]{6})/g;
  let match;
  while ((match = re.exec(css)) !== null) {
    vars.set(`--${match[1]}`, match[2].toUpperCase());
  }
  return vars;
}

function channel(value) {
  const c = value / 255;
  return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
}

function luminance(hex) {
  const h = hex.replace("#", "");
  const r = channel(parseInt(h.slice(0, 2), 16));
  const g = channel(parseInt(h.slice(2, 4), 16));
  const b = channel(parseInt(h.slice(4, 6), 16));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function contrast(a, b) {
  const l1 = luminance(a);
  const l2 = luminance(b);
  const hi = Math.max(l1, l2);
  const lo = Math.min(l1, l2);
  return (hi + 0.05) / (lo + 0.05);
}

const css = fs.readFileSync(tokensPath, "utf8");
const vars = parseHexVars(css);
const white = vars.get("--white");
if (!white) throw new Error("Missing --white in tokens.css");

const pairs = [
  { name: "Body text", fg: "--neutral-800", bg: "--white", min: 4.5, sc: "1.4.3" },
  { name: "Placeholder", fg: "--neutral-400", bg: "--white", min: 4.5, sc: "1.4.3" },
  { name: "Control border", fg: "--neutral-300", bg: "--white", min: 3.0, sc: "1.4.11" },
  { name: "Primary fill / link", fg: "--brand-600", bg: "--white", min: 4.5, sc: "1.4.3" },
  { name: "Focus ring", fg: "--focus-500", bg: "--white", min: 3.0, sc: "1.4.11" },
  { name: "Info badge", fg: "--info-700", bg: "--info-100", min: 4.5, sc: "1.4.3" },
  { name: "Success badge", fg: "--success-700", bg: "--success-100", min: 4.5, sc: "1.4.3" },
  { name: "Warning badge", fg: "--warning-700", bg: "--warning-100", min: 4.5, sc: "1.4.3" },
  { name: "Error badge", fg: "--error-700", bg: "--error-100", min: 4.5, sc: "1.4.3" },
  { name: "White on primary", fg: "--white", bg: "--brand-600", min: 4.5, sc: "1.4.3" },
];

const rows = [];
let failed = 0;
for (const pair of pairs) {
  const fg = vars.get(pair.fg);
  const bg = vars.get(pair.bg);
  if (!fg || !bg) {
    rows.push({ ...pair, fgHex: fg || "missing", bgHex: bg || "missing", ratio: 0, pass: false });
    failed += 1;
    continue;
  }
  const ratio = contrast(fg, bg);
  const pass = ratio + 1e-9 >= pair.min;
  if (!pass) failed += 1;
  rows.push({ ...pair, fgHex: fg, bgHex: bg, ratio, pass });
}

const decorative = {
  name: "Decorative border",
  token: "--neutral-200",
  hex: vars.get("--neutral-200") || "missing",
  ratio: vars.get("--neutral-200") ? contrast(vars.get("--neutral-200"), white) : 0,
};

const lines = [];
lines.push("# Accessibility baseline");
lines.push("");
lines.push("Generated from `tokens.css` by `scripts/check-contrast.mjs`.");
lines.push("Do not edit this file by hand. Re-run the script after token changes.");
lines.push("");
lines.push("Pairs use WCAG 2.2 contrast: **4.5:1** for text (SC 1.4.3), **3:1** for UI (SC 1.4.11).");
lines.push("`--border-default` (`--neutral-200`) is decorative. It must not be the only cue on a control edge.");
lines.push("`--hit-target` aliases `--control-height` (44px). Compact controls use `--control-height-sm` (32px).");
lines.push("`prefers-reduced-motion` sets `--motion-duration` to `0ms`. `forced-colors` restyles focus and borders in `components.css`.");
lines.push("");
lines.push("| Pair | Foreground | Background | Ratio | Required | Result |");
lines.push("|---|---|---|---:|---:|---|");
for (const row of rows) {
  lines.push(
    `| ${row.name} (${row.sc}) | \`${row.fg}\` ${row.fgHex} | \`${row.bg}\` ${row.bgHex} | ${row.ratio.toFixed(2)}:1 | ${row.min.toFixed(1)} | ${row.pass ? "pass" : "**fail**"} |`,
  );
}
lines.push(
  `| ${decorative.name} | \`${decorative.token}\` ${decorative.hex} | \`--white\` ${white} | ${decorative.ratio.toFixed(2)}:1 | n/a (decorative) | documented |`,
);
lines.push("");
lines.push("Run:");
lines.push("");
lines.push("```bash");
lines.push("node scripts/check-contrast.mjs");
lines.push("```");
lines.push("");

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, lines.join("\n"));

if (failed > 0) {
  console.error(`Contrast check failed: ${failed} pair(s) below threshold. See ${path.relative(root, outPath)}`);
  process.exit(1);
}
console.log(`Contrast check passed. Wrote ${path.relative(root, outPath)}`);
